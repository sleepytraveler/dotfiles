-- Markdown setup

vim.opt_local.wrap = true -- Soft-wrap long lines
vim.opt_local.linebreak = true -- Wrap at words instead of hard breaking characters
vim.opt_local.spell = true -- Enable spell check
vim.opt_local.spelllang = "en_us" -- Set spell check language
vim.opt_local.conceallevel = 2 -- Hide markdown syntax markers (like ** or _) unless editing the line
vim.opt_local.tabstop = 2 -- Use 2 spaces to indent
vim.opt_local.tabstop = 2 -- Width that a \t character displays as
vim.opt_local.shiftwidth = 2 -- Number of spaces to use for each step of (auto)indent
vim.opt_local.softtabstop = 2 -- Number of spaces that a Tab counts for while editing
vim.opt_local.expandtab = true -- Convert tabs into spaces
